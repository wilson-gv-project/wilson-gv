def test__styled_print_terminal(monkeypatch):
    buf = io.StringIO()
    # Fake a terminal with isatty = True
    monkeypatch.setattr(buf, "isatty", lambda: True)
    wprinting._styled_print("LABEL", "93", "styled msg", file=buf)
    value = buf.getvalue()
    assert "\033[93m" in value
    assert "[LABEL] styled msg" in value


