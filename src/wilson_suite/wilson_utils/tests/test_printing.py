def strip_ansi(text):
    """Remove ANSI escape codes (for tests)."""
    return re.sub(r'\x1b\[[0-9;]*m', '', text)


def test_infoprint():
    buf = io.StringIO()
    wprinting.infoprint("info message", file=buf)
    assert strip_ansi(buf.getvalue()).strip() == "[INFO] info message"


def test_debugprint():
    buf = io.StringIO()
    wprinting.debugprint("debug value", 123, file=buf)
    assert strip_ansi(buf.getvalue()).strip() == "[DEBUG] debug value 123"


def test_printtest():
    buf = io.StringIO()
    wprinting.printtest("test log", file=buf)
    assert strip_ansi(buf.getvalue()).strip() == "[TESTPRINT] test log"


